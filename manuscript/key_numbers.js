// Headline numbers used in the abstract and discussion (all computed from paper_numbers.json).
module.exports = function (N) {
  const U = require("./results_util")(N);
  const { T, f, pct, pv } = U;
  const get = (t, m) => T(t).find((r) => r.model === m);
  const K = {};
  K.fallsAUROC = f(get("T3_benchmark_falls", "CARES (dual-view)").AUROC, 4);
  K.fogAUROC = f(get("T3_benchmark_fog", "CARES (dual-view)").AUROC);
  K.fogThr = f(get("T3_benchmark_fog", "Threshold").AUROC);
  K.harF1 = f(get("T3_benchmark_har70", "CARES (dual-view)").MacroF1);
  const per = T("S2_per_subject_fog").filter((r) => r.model === "CARES (dual-view)" && r.AUROC !== null).map((r) => r.AUROC);
  K.fogRange = `${f(Math.min(...per))}–${f(Math.max(...per))}`;
  const CG = T("T7_cognitive_surveillance");
  const best = (t) => CG.filter((r) => r.task.startsWith(t)).reduce((x, y) => (y.AUROC > x.AUROC ? y : x));
  K.cogBestA = f(best("A").AUROC);
  K.cogDem = f(best("C").AUROC);
  K.cogMci = f(best("D").AUROC);
  const AF = T("T6_alarm_budget_fog");
  const a = (t, p, b) => T(t).find((r) => r.policy === p && r.budget_per_h === b);
  K.fogB = 4;
  K.fogYoudenFA = f(a("T6_alarm_budget_fog", "Youden (window-optimal)", 4).median_fa_per_h, 2);
  K.fogNaiveCov = pct(a("T6_alarm_budget_fog", "naive pooled calibration", 4).coverage, 1);
  K.fogConfCov = pct(a("T6_alarm_budget_fog", "conformal (proposed)", 4).coverage, 1);
  K.fogConfSens = pct(a("T6_alarm_budget_fog", "conformal (proposed)", 4).episode_sensitivity, 1);
  K.target = "90.0%";
  const l0 = a("T6_alarm_budget_falls", "conformal (proposed)", 0), ly = a("T6_alarm_budget_falls", "Youden (window-optimal)", 0);
  K.fallsConfCov = pct(l0.coverage, 1);
  K.fallsConfSens = pct(l0.fall_sensitivity, 1);
  K.fallsYoudenFA = f(ly.pooled_fa_per_h, 2);
  K.fallsYoudenCov = pct(ly.coverage, 1);
  K.fallsConfFA = f(l0.pooled_fa_per_h, 2);
  K.fallsAlarmSentence = `For falls on continuous streams, the window-optimal threshold produced ${K.fallsYoudenFA} false alarms per hour of daily activity and left only ${K.fallsYoudenCov} of people without any false alarm, whereas the conformal threshold kept ${K.fallsConfCov} of new people entirely free of false alarms during their ADL protocol (pooled ${K.fallsConfFA} per hour) while detecting ${K.fallsConfSens} of falls.`;
  const E = T("T4_ecg_arrhythmia").filter((r) => r.eval === "DS2 after 5 min");
  const er = (sc, m) => E.find((r) => r.scenario.startsWith(sc) && r.model === m);
  K.ecgGlobal = f(er("A", "CARES (dual-view)").MacroF1_NSV);
  K.ecgAdaptive = f(er("B", "CARES (dual-view)").MacroF1_NSV);
  K.ecgSeS = f(er("B", "CARES (dual-view)").Se_S);
  K.ecgPpvS = f(er("B", "CARES (dual-view)").PPV_S);
  K.ecgFlFt = f(er("C", "FedAvg MLP + on-device fine-tuning").MacroF1_NSV);
  K.ecgFl = f(er("C", "FedAvg MLP").MacroF1_NSV);
  K.ecgRho = f(T("T4b_ecg_burden").find((r) => r.model.includes("adaptive") && r.beat === "VEB").spearman_rho);
  const fl = (s, m) => T(`T5_federated_personalised_${s}`).find((r) => r.method === m);
  K.fogFed = f(fl("fog", "FedAvg MLP").AUROC); K.fogCen = f(fl("fog", "Central MLP").AUROC);
  K.harFed = f(fl("har70", "FedAvg MLP").MacroF1); K.harCen = f(fl("har70", "Central MLP").MacroF1);
  K.harFt5 = f(fl("har70", "FedAvg + FT (5 min)").MacroF1); K.harLoc5 = f(fl("har70", "Local only (5 min)").MacroF1);
  K.flSentence = `Federated training reached ${K.fogFed} AUROC for FoG (centralised: ${K.fogCen}) and ${K.harFed} macro-F1 for activity (centralised: ${K.harCen}), and for ECG, on-device fine-tuning of the federated model raised macro-F1 from ${K.ecgFl} to ${K.ecgFlFt}; a model trained locally on 5 minutes of a person's own data was far weaker (activity macro-F1 ${K.harLoc5}).`;
  // ---- revision: coverage with exact CIs, best global ECG model, personalisation remedies
  const CI = T("T6e_coverage_ci");
  const ci_ = (svc, p, b) => CI.find((r) => r.service === svc && r.policy === p && r.budget_per_h === b);
  const cc = (r) => `${r.covered} of ${r.people}`;
  const cr = (r) => `${pct(r.coverage_lo, 1)}–${pct(r.coverage_hi, 1)}`;
  K.fallsConfN = cc(ci_("Falls", "conformal (proposed)", 0)); K.fallsConfCI = cr(ci_("Falls", "conformal (proposed)", 0));
  K.fallsYoudenN = cc(ci_("Falls", "Youden (window-optimal)", 0));
  K.fogConfN = cc(ci_("FoG", "conformal (proposed)", 4)); K.fogConfCI = cr(ci_("FoG", "conformal (proposed)", 4));
  K.fogNaiveN = cc(ci_("FoG", "naive pooled calibration", 4)); K.fogNaiveCI = cr(ci_("FoG", "naive pooled calibration", 4));
  K.fogMcNemar = pv(ci_("FoG", "naive pooled calibration", 4).mcnemar_p_vs_conformal);
  const A_ = E.filter((r) => r.scenario.startsWith("A"));
  const bg = A_.reduce((x, y) => (y.MacroF1_NSV > x.MacroF1_NSV ? y : x));
  K.ecgBestGlobal = f(bg.MacroF1_NSV); K.ecgBestGlobalModel = bg.model === "RF" ? "random forest" : bg.model;
  const PC = T("S13_ecg_per_class");
  K.ecg5Global = f(PC.find((r) => r.scenario === "global" && r.model === "CARES (dual-view)").MacroF1_NSVFQ);
  K.ecg5Adaptive = f(PC.find((r) => r.scenario === "patient-adaptive" && r.model === "CARES (dual-view)").MacroF1_NSVFQ);
  K.harFt1 = f(fl("har70", "FedAvg + FT (1 min)").MacroF1);
  const LT = T("T10_gateway_latency"), BW = T("T11_bandwidth"), SIM = T("T12_alert_delivery_simulation");
  K.latencyFog = f(LT.find((r) => r.service === "fog").median_ms_per_window, 1);
  K.latencyMax = f(Math.max(...LT.map((r) => r.median_ms_per_window)), 1);
  K.bwFactor = f(Math.min(...BW.map((r) => r.reduction_vs_raw)), 0);
  K.bwFactorMax = f(Math.max(...BW.map((r) => r.reduction_vs_raw)), 0);
  K.deliv60 = pct(SIM.find((r) => r.scenario === "packet loss 5%").within_60s, 1);
  return K;
};
